// Command notices writes internal/notices/THIRD_PARTY_NOTICES.txt: Longarm's
// own license and the license texts (LICENSE, COPYING, NOTICE, PATENTS ...)
// of everything the releases carry - the Go modules linked into the
// binaries (every cmd/, on every platform and build tag the releases use,
// and Go's standard library), the web UI's runtime packages (internal/webui:
// the hub panel and the tray; fonts included) and the hub image's
// Litestream with its modules (deploy/hub/image-build.sh's version). The
// binaries embed it (`longarm licenses`, internal/notices), the hub panel
// and the tray show it, and every package installs it.
//
// Run it from the repository root after changing a dependency and commit
// what it wrote (CI's web job runs -check):
//
//	go run ./packaging/notices          # needs web/node_modules (pnpm install)
//	go run ./packaging/notices -check   # fails when the file is out of date
//
// It fails, too, when a dependency's license is not a permissive one it
// knows (MIT, BSD, Apache-2.0, ISC, ...): copyleft or unknown licenses need
// a decision first (docs/licenses.md), recorded in reviewed below.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

const out = "internal/notices/THIRD_PARTY_NOTICES.txt"

// targets: the platforms and build tags of the released binaries (the tray:
// production, native on Linux with cgo; macOS with cgo).
var targets = []struct{ goos, goarch, cgo, tags string }{
	{"windows", "amd64", "0", ""},
	{"windows", "amd64", "0", "production"},
	{"windows", "arm64", "0", "production"},
	{"linux", "amd64", "0", ""},
	{"linux", "amd64", "0", "production"},
	{"linux", "amd64", "1", "production traynative"},
	{"linux", "arm64", "0", "production"},
	{"darwin", "arm64", "0", "production"},
	{"darwin", "arm64", "1", "production"},
	{"darwin", "amd64", "0", ""},
}

// permissive: the licenses that need nothing but their notice kept.
var permissive = map[string]bool{
	"MIT": true, "MIT-0": true, "BSD-2-Clause": true, "BSD-3-Clause": true, "Apache-2.0": true,
	"ISC": true, "0BSD": true, "Unlicense": true, "CC0-1.0": true, "BlueOak-1.0.0": true, "OFL-1.1": true,
}

// reviewed: dependencies whose license the check can't classify as
// permissive, each with the reason it is fine (docs/licenses.md).
var reviewed = map[string]string{}

type file struct{ name, text string }

type dep struct {
	name, version string
	license       string // the primary license files' kinds, " / "-joined
	files         []file
}

func main() {
	check := flag.Bool("check", false, "fail when "+out+" is out of date instead of writing it")
	flag.Parse()
	text, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
	if *check {
		old, _ := os.ReadFile(out)
		if string(bytes.ReplaceAll(old, []byte("\r\n"), []byte("\n"))) != text {
			fmt.Fprintf(os.Stderr, "notices: %s is out of date: run go run ./packaging/notices and commit it\n", out)
			os.Exit(1)
		}
		fmt.Println("notices:", out, "is up to date")
		return
	}
	if err := os.WriteFile(out, []byte(text), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
	fmt.Println("notices: wrote", out)
}

func generate() (string, error) {
	own, err := os.ReadFile("LICENSE")
	if err != nil {
		return "", err
	}
	goDeps, err := goModules()
	if err != nil {
		return "", err
	}
	webDeps, err := webPackages()
	if err != nil {
		return "", err
	}
	lsDeps, lsVer, err := litestream()
	if err != nil {
		return "", err
	}
	var bad []string
	for _, ds := range [][]dep{goDeps, webDeps, lsDeps} {
		for _, d := range ds {
			if _, ok := reviewed[d.name]; ok {
				continue
			}
			for _, l := range strings.Split(d.license, " / ") {
				if !permissive[l] {
					bad = append(bad, fmt.Sprintf("%s %s: %s", d.name, d.version, d.license))
					break
				}
			}
		}
	}
	if len(bad) > 0 {
		return "", fmt.Errorf("licenses that are not known permissive ones (review them, docs/licenses.md; then add them to reviewed in packaging/notices):\n  %s", strings.Join(bad, "\n  "))
	}

	var b strings.Builder
	rule := strings.Repeat("=", 80)
	b.WriteString(`Longarm: license and third-party notices
========================================

Generated by "go run ./packaging/notices" - do not edit. Also printed by
"longarm licenses" (and longarmd, longarm-hub, longarm-relay) and served by
the hub panel at /licenses.txt.

Longarm itself is licensed under the MIT License:

`)
	b.WriteString(normalize(string(own)))
	b.WriteString(`
Longarm's binaries, web UI and hub container image include the third-party
software below, each under its own license, reproduced in full after the
lists. The hub container image is based on Google's distroless
static-debian12 image, whose Debian packages (ca-certificates, base-files,
netbase, tzdata ...) keep their own copyright files in /usr/share/doc; their
sources are at https://sources.debian.org.

`)
	sections := []struct {
		title string
		deps  []dep
	}{
		{"Go modules (longarm, longarmd, longarm-hub, longarm-relay, longarm-tray, longarm-update)", goDeps},
		{"Web UI packages (the hub panel and the tray: internal/webui)", webDeps},
		{"longarm-hub container image: Litestream " + lsVer + " and its Go modules", lsDeps},
	}
	for _, s := range sections {
		fmt.Fprintf(&b, "%s\n%s\n", s.title, strings.Repeat("-", len(s.title)))
		for _, d := range s.deps {
			fmt.Fprintf(&b, "  %-58s %-40s %s\n", d.name, d.version, d.license)
		}
		b.WriteString("\n")
	}
	seen := map[string]string{} // a license text -> where it was written
	for _, s := range sections {
		for _, d := range s.deps {
			fmt.Fprintf(&b, "%s\n%s %s\nLicense: %s\n%s\n", rule, d.name, d.version, d.license, rule)
			for _, f := range d.files {
				// a text the same as an earlier one (Apache-2.0's, mostly):
				// written once, referred to after
				if first, ok := seen[f.text]; ok {
					fmt.Fprintf(&b, "\n--- %s ---\n\n(the same text as %s above)\n", f.name, first)
					continue
				}
				seen[f.text] = fmt.Sprintf("%s %s's %s", d.name, d.version, f.name)
				fmt.Fprintf(&b, "\n--- %s ---\n\n%s", f.name, f.text)
			}
			b.WriteString("\n")
		}
	}
	return b.String(), nil
}

// goModules: the modules every cmd/ links on the targets, and Go's
// standard library.
func goModules() ([]dep, error) {
	mods := map[string][2]string{} // path -> version, dir
	for _, t := range targets {
		env := []string{"GOOS=" + t.goos, "GOARCH=" + t.goarch, "CGO_ENABLED=" + t.cgo}
		args := []string{"list", "-deps", "-f", listFmt}
		if t.tags != "" {
			args = append(args, "-tags", t.tags)
		}
		o, err := goCmd("", env, append(args, "./cmd/...")...)
		if err != nil {
			return nil, err
		}
		parseList(o, mods, false)
	}
	ds, err := modDeps(mods)
	if err != nil {
		return nil, err
	}
	// the standard library and runtime: the go directive's version
	gomod, _ := os.ReadFile("go.mod")
	ver := "go" + regexp.MustCompile(`(?m)^go (\S+)`).FindStringSubmatch(string(gomod))[1]
	root, err := goCmd("", nil, "env", "GOROOT")
	if err != nil {
		return nil, err
	}
	std, err := licenseFiles(strings.TrimSpace(root))
	if err != nil {
		return nil, fmt.Errorf("Go standard library: %w", err)
	}
	return append([]dep{{name: "Go (standard library and runtime)", version: ver, license: kinds(std), files: std}}, ds...), nil
}

// listFmt: a package's module (path, version, dir; a replacement's version
// and dir when replaced), main module marked.
const listFmt = `{{with .Module}}{{.Path}}	{{if .Replace}}{{.Replace.Version}}	{{.Replace.Dir}}{{else}}{{.Version}}	{{.Dir}}{{end}}	{{.Main}}{{end}}`

func parseList(o string, mods map[string][2]string, withMain bool) {
	for _, l := range strings.Split(o, "\n") {
		f := strings.Split(strings.TrimSpace(l), "\t")
		if len(f) != 4 || (f[3] == "true" && !withMain) {
			continue
		}
		mods[f[0]] = [2]string{f[1], f[2]}
	}
}

func modDeps(mods map[string][2]string) ([]dep, error) {
	var ds []dep
	for p, vd := range mods {
		fs, err := licenseFiles(vd[1])
		if err != nil {
			return nil, fmt.Errorf("%s %s: %w", p, vd[0], err)
		}
		ds = append(ds, dep{name: p, version: vd[0], license: kinds(fs), files: fs})
	}
	slices.SortFunc(ds, func(a, b dep) int { return strings.Compare(a.name, b.name) })
	return ds, nil
}

// webPackages: the web UI's runtime packages (pnpm's --prod list:
// dependencies and theirs; vite bundles them into internal/webui/dist).
func webPackages() ([]dep, error) {
	cmd := exec.Command("pnpm", "licenses", "list", "--prod", "--json")
	cmd.Dir = "web"
	cmd.Stderr = os.Stderr
	o, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("pnpm licenses list (run pnpm install in web/ first): %w", err)
	}
	var byLicense map[string][]struct {
		Name     string   `json:"name"`
		Versions []string `json:"versions"`
		Paths    []string `json:"paths"`
	}
	if err := json.Unmarshal(o, &byLicense); err != nil {
		return nil, fmt.Errorf("pnpm licenses list: %w", err)
	}
	var ds []dep
	for _, ps := range byLicense {
		for _, p := range ps {
			for i, v := range p.Versions {
				if i >= len(p.Paths) {
					break
				}
				fs, err := licenseFiles(p.Paths[i])
				if err != nil {
					return nil, fmt.Errorf("%s %s: %w", p.Name, v, err)
				}
				ds = append(ds, dep{name: p.Name, version: v, license: kinds(fs), files: fs})
			}
		}
	}
	slices.SortFunc(ds, func(a, b dep) int { return strings.Compare(a.name+" "+a.version, b.name+" "+b.version) })
	return ds, nil
}

// litestream: the Litestream the hub image installs (its version from
// deploy/hub/image-build.sh) and the modules its binary links (linux).
func litestream() ([]dep, string, error) {
	sh, err := os.ReadFile("deploy/hub/image-build.sh")
	if err != nil {
		return nil, "", err
	}
	m := regexp.MustCompile(`lsmod=(\S+)\s+lsver=\$\{LITESTREAM_VERSION:-([^}]+)\}`).FindStringSubmatch(string(sh))
	if m == nil {
		return nil, "", errors.New("deploy/hub/image-build.sh: no lsmod= / lsver= (Litestream's module and version)")
	}
	mod, ver := m[1], m[2]
	o, err := goCmd("", nil, "mod", "download", "-json", mod+"@"+ver)
	if err != nil {
		return nil, "", err
	}
	var dl struct{ Dir string }
	if err := json.Unmarshal([]byte(o), &dl); err != nil || dl.Dir == "" {
		return nil, "", fmt.Errorf("go mod download %s@%s: no directory", mod, ver)
	}
	mods := map[string][2]string{}
	for _, arch := range []string{"amd64", "arm64"} {
		o, err := goCmd(dl.Dir, []string{"GOOS=linux", "GOARCH=" + arch, "CGO_ENABLED=0", "GOFLAGS=-mod=mod"}, "list", "-deps", "-f", listFmt, "./cmd/litestream")
		if err != nil {
			return nil, "", err
		}
		parseList(o, mods, true)
	}
	// the main module lists without a version
	mods[mod] = [2]string{ver, dl.Dir}
	ds, err := modDeps(mods)
	return ds, ver, err
}

func goCmd(dir string, env []string, args ...string) (string, error) {
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), env...)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	o, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("go %s (%s): %w\n%s", strings.Join(args, " "), strings.Join(env, " "), err, stderr.String())
	}
	return string(o), nil
}

// licenseFile: LICENSE, LICENCE, COPYING, NOTICE, PATENTS, UNLICENSE, with
// any suffix (LICENSE.txt, LICENSE-MIT, NOTICE.md ...); not code.
var licenseFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|patents|unlicense)([._-][\w.-]*)?$`)
var codeExt = regexp.MustCompile(`(?i)\.(go|js|mjs|cjs|ts|json|ya?ml|py|sh|html|css)$`)

// primary: the license files proper (not NOTICE, PATENTS or a list of
// someone else's licenses).
var primary = regexp.MustCompile(`(?i)^(licen[cs]e|copying|unlicense)([._-](txt|md|markdown|rst|mit|apache|apache-2\.0|bsd|isc|ofl))?$`)

func licenseFiles(dir string) ([]file, error) {
	ents, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var fs []file
	hasPrimary := false
	for _, e := range ents {
		n := e.Name()
		if e.IsDir() || !licenseFile.MatchString(n) || codeExt.MatchString(n) {
			continue
		}
		b, err := os.ReadFile(filepath.Join(dir, n))
		if err != nil {
			return nil, err
		}
		fs = append(fs, file{name: n, text: normalize(string(b))})
		hasPrimary = hasPrimary || primary.MatchString(n)
	}
	if !hasPrimary {
		return nil, fmt.Errorf("no license file in %s", dir)
	}
	slices.SortFunc(fs, func(a, b file) int { return strings.Compare(strings.ToLower(a.name), strings.ToLower(b.name)) })
	return fs, nil
}

func normalize(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	s = strings.TrimPrefix(s, string(rune(0xFEFF))) // a byte order mark
	return strings.TrimRight(s, " \n\t") + "\n"
}

// kinds: the primary files' licenses, " / "-joined.
func kinds(fs []file) string {
	var ks []string
	for _, f := range fs {
		if !primary.MatchString(f.name) {
			continue
		}
		if k := classify(f.text); !slices.Contains(ks, k) {
			ks = append(ks, k)
		}
	}
	return strings.Join(ks, " / ")
}

// classify: a license text's SPDX identifier, by its wording; "unknown"
// when none matches.
func classify(t string) string {
	t = strings.Join(strings.Fields(t), " ") // line breaks anywhere
	has := func(s ...string) bool {
		for _, x := range s {
			if !strings.Contains(t, x) {
				return false
			}
		}
		return true
	}
	switch {
	case has("GNU AFFERO GENERAL PUBLIC LICENSE"):
		return "AGPL"
	case has("GNU LESSER GENERAL PUBLIC LICENSE"), has("GNU LIBRARY GENERAL PUBLIC LICENSE"):
		return "LGPL"
	case has("GNU GENERAL PUBLIC LICENSE"):
		return "GPL"
	case has("Mozilla Public License"):
		return "MPL-2.0"
	case has("Eclipse Public License"):
		return "EPL"
	case has("COMMON DEVELOPMENT AND DISTRIBUTION LICENSE"):
		return "CDDL"
	case has("SIL OPEN FONT LICENSE"):
		return "OFL-1.1"
	case has("Apache License", "Version 2.0"):
		return "Apache-2.0"
	case has("This is free and unencumbered software released into the public domain"):
		return "Unlicense"
	case has("Blue Oak Model License"):
		return "BlueOak-1.0.0"
	case has("Permission is hereby granted, free of charge"):
		if !strings.Contains(t, "The above copyright notice and this permission notice shall be included") {
			return "MIT-0"
		}
		return "MIT"
	case has("Redistribution and use in source and binary forms"):
		if has("endorse or promote products") {
			return "BSD-3-Clause"
		}
		return "BSD-2-Clause"
	case has("Permission to use, copy, modify, and/or distribute this software for any"):
		if has("above copyright notice and this permission notice appear in all copies") {
			return "ISC"
		}
		return "0BSD"
	case has("Permission to use, copy, modify, and distribute this software for any purpose"):
		return "ISC"
	case has("CC0 1.0 Universal"):
		return "CC0-1.0"
	}
	return "unknown"
}
